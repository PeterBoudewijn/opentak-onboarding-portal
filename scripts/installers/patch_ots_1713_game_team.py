#!/usr/bin/env python3
"""Apply the Airsoft GameRed/GameBlue team-color override to OpenTAKServer 1.7.13.

Run this script with the Python interpreter from the OpenTAKServer 1.7.13
virtualenv. It locates the installed EudHandler.py, creates a timestamped
backup, applies an idempotent source patch, and byte-compiles the result.

The patch only changes CoT generated by authenticated users that have an
enabled IN membership in exactly one reserved group:
  GameRed  -> __group name="Red",  role="Team Member"
  GameBlue -> __group name="Blue", role="Team Member"

All other OTS users and groups are left untouched.
"""

from __future__ import annotations

import importlib.util
import py_compile
import shutil
import sys
from datetime import datetime
from pathlib import Path

MARKER = "# AIRSOFT_GAME_TEAM_OVERRIDE_V1"

INIT_OLD = """    def __init__(self, request: socket, client_address, server):
        super().__init__(request, client_address, server)
        self.logger = logging.getLogger()
        self.socket: socket = request
"""

INIT_NEW = """    def __init__(self, request: socket, client_address, server):
        super().__init__(request, client_address, server)
        self.logger = logging.getLogger()
        self.socket: socket = request
        # Per-connection state for the game-only team override.
        self.airsoft_game_team = None
        self.airsoft_game_team_checked = False
"""

HELPER_ANCHOR = """    def handle_cot(self, cot):
"""

HELPER = """    # AIRSOFT_GAME_TEAM_OVERRIDE_V1
    def _apply_airsoft_game_team(self, event):
        \"\"\"Force reserved game accounts to publish the configured team color.

        OTS normally forwards the client's raw CoT, including its __group
        value. iTAK can therefore keep publishing Cyan even when the OTS user
        belongs only to GameRed/GameBlue. Resolve the authenticated user's
        reserved IN group once per socket and rewrite only that user's CoT.
        \"\"\"
        if not event or not self.is_ssl or not self.user:
            return

        if not self.airsoft_game_team_checked:
            with self.app.app_context():
                memberships = db.session.execute(
                    db.session.query(GroupUser).filter_by(
                        user_id=self.user.id,
                        direction=Group.IN,
                        enabled=True,
                    )
                ).all()

                group_names = {
                    membership[0].group.name
                    for membership in memberships
                    if membership and membership[0].group
                }

            reserved = [
                group_name
                for group_name in ("GameRed", "GameBlue")
                if group_name in group_names
            ]

            if len(reserved) == 1:
                self.airsoft_game_team = {
                    "GameRed": "Red",
                    "GameBlue": "Blue",
                }[reserved[0]]
                self.logger.info(
                    "Airsoft game team override for %s: %s",
                    self.user.username,
                    self.airsoft_game_team,
                )
            elif len(reserved) > 1:
                self.logger.warning(
                    "Airsoft game team override skipped for %s: user belongs to both reserved groups",
                    self.user.username,
                )

            self.airsoft_game_team_checked = True

        if not self.airsoft_game_team:
            return

        group = event.find("__group")
        if group:
            group.attrs["name"] = self.airsoft_game_team
            group.attrs["role"] = "Team Member"
            return

        # Be defensive if a client omits __group. Add it under <detail> so
        # downstream clients still receive the game identity.
        detail = event.find("detail")
        if detail:
            group = BeautifulSoup(
                '<__group role="Team Member" name="{}"/>'.format(self.airsoft_game_team),
                "xml",
            ).find("__group")
            detail.append(group)

"""

CALL_OLD = """        if self.pong(event):
            return

        if event and not self.uid:
"""

CALL_NEW = """        if self.pong(event):
            return

        self._apply_airsoft_game_team(event)

        if event and not self.uid:
"""


def locate_target() -> Path:
    spec = importlib.util.find_spec("opentakserver.eud_handler.EudHandler")
    if spec is None or not spec.origin:
        raise RuntimeError(
            "Could not locate opentakserver.eud_handler.EudHandler. "
            "Run this script with the OpenTAKServer 1.7.13 virtualenv Python."
        )
    return Path(spec.origin).resolve()


def main() -> int:
    target = locate_target()
    source = target.read_text(encoding="utf-8")

    print(f"Target: {target}")

    if MARKER in source:
        print("Patch is already installed; no changes made.")
        return 0

    for label, needle in (
        ("EudHandler.__init__", INIT_OLD),
        ("handle_cot insertion point", HELPER_ANCHOR),
        ("handle_cot call site", CALL_OLD),
    ):
        if needle not in source:
            raise RuntimeError(
                f"Expected OpenTAKServer 1.7.13 source pattern not found: {label}. "
                "Refusing to modify the file."
            )

    patched = source.replace(INIT_OLD, INIT_NEW, 1)
    patched = patched.replace(HELPER_ANCHOR, HELPER + HELPER_ANCHOR, 1)
    patched = patched.replace(CALL_OLD, CALL_NEW, 1)

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = target.with_name(target.name + f".bak-airsoft-team-{stamp}")
    shutil.copy2(target, backup)

    try:
        target.write_text(patched, encoding="utf-8")
        py_compile.compile(str(target), doraise=True)
    except Exception:
        shutil.copy2(backup, target)
        raise

    print(f"Backup: {backup}")
    print("Patch installed and Python compile check passed.")
    print("Restart opentakserver-1713.service to activate it.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
